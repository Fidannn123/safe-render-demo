"""EVIDENCE.md, generated from metrics.json, run.json and verify output. No number is typed by hand."""

from __future__ import annotations

from pathlib import Path
from typing import Any

CONFIG_NAMES = {
    "B0": "Undefended agent with direct transfer rights",
    "B1": "Guardian + permission tiers",
    "B2": "Guardian + tiers + privacy-preserving fraud network",
}
WHY = {
    "GUARDED": "T2: new or changed payee under the new-payee caps; paid after the cool-off (no owner veto)",
    "ALLOW": "T1: known payee within caps",
    "PAID": "paid the account printed on the invoice",
    "EXPOSED": "a stolen agent credential is a bank credential",
}


def pct(value: float | None) -> str:
    return "not measured" if value is None else f"{value * 100:.1f}%"


def usd(minor: int) -> str:
    return f"USD {minor / 100:,.2f}"


def ms(value: float | None) -> str:
    return "not measured" if value is None else f"{value:.1f} ms"


def row(label: str, configs: dict[str, Any], cell: Any) -> str:
    return f"| {label} | " + " | ".join(cell(configs[k]) for k in configs) + " |"


def results(c: dict[str, Any]) -> list[str]:
    return [
        "| Measure | B0 | B1 | B2 |",
        "|---|---|---|---|",
        row("Scenarios scored / executed", c, lambda v: f"{v['scenarios']} / {v['executed']}"),
        row("Behaved as designed (PASS)", c, lambda v: f"{v['passed']} / {v['executed']}"),
        row("Attacker loss", c, lambda v: usd(v["attacker_loss_minor"])),
        row("Attack success rate", c, lambda v: pct(v["attack_success_rate"])),
        row("Benign task success", c, lambda v: pct(v["benign_success_rate"])),
        row("False holds on benign payments", c, lambda v: pct(v["false_hold_rate"])),
        row("Ambiguous invoices held", c, lambda v: pct(v["ambiguous_held_rate"])),
        row(
            "Decision latency p50 / p95",
            c,
            lambda v: f"{ms(v['latency_ms']['p50'])} / {ms(v['latency_ms']['p95'])}",
        ),
    ]


def residual(metrics: dict[str, Any]) -> list[str]:
    lines = [
        "| Config | Scenario | Class | Outcome | Loss | Why it got through |",
        "|---|---|---|---|---|---|",
    ]
    for config in ("B1", "B2"):
        for item in metrics["residual_attacks"][config]:
            outcome = item["verdict"] or "?"
            lines.append(
                f"| {config} | {item['scenario_id']} | {item['scenario_class']} | {outcome} "
                f"{item['tier'] or ''} | {usd(item['loss_minor'])} | {WHY.get(outcome, 'see ops.jsonl')} |"
            )
    return lines if len(lines) > 2 else ["None: no attack moved money in B1 or B2."]


def render(metrics: dict[str, Any], run: dict[str, Any], verified: dict[str, Any]) -> str:
    c = metrics["configs"]
    seed = metrics["seed"]
    alerts, analysis, network = metrics["cashflow_alerts"], metrics["financial_analysis"], metrics["network"]
    tasks = ["| Task (B1) | Passed / executed |", "|---|---|"]
    tasks += [f"| {task} | {v['passed']} / {v['executed']} |" for task, v in c["B1"]["tasks"].items()]
    lines = [
        f"# SafePay evidence, {metrics['run_id']}",
        "",
        f"> {metrics['disclosure']}",
        "",
        f"Generated by `make evidence SEED={seed}`; re-checked by `make verify-evidence SEED={seed}`.",
        f"Run started {run['started_at']} and finished {run['finished_at']} (wall clock). {metrics['mode']}.",
        "",
        "## Configurations",
        "",
        *(f"- **{k}**: {v}" for k, v in CONFIG_NAMES.items()),
        "",
        "## Results",
        "",
        *results(c),
        "",
        "## Agent tasks",
        "",
        *tasks,
        "",
        f"- Cash-flow alerts vs the twins' independent forecast: precision {pct(alerts['precision'])}, "
        f"recall {pct(alerts['recall'])} ({alerts['true_positive_weeks']} true, "
        f"{alerts['false_positive_weeks']} false, {alerts['false_negative_weeks']} missed alert weeks).",
        f"- Financial analysis answers matching the oracle exactly: "
        f"{analysis['exact_matches']} / {analysis['answers']}.",
        "",
        "## Attacks that still moved money",
        "",
        *residual(metrics),
        "",
        "## Fraud network",
        "",
        f"- Reported-payee scenarios: {network['reported_payee_scenarios']}; stopped before payment in B1: "
        f"{network['stopped_before_payment_b1']}, in B2: {network['stopped_before_payment_b2']}; "
        f"detection lift {pct(metrics['network_detection_lift'])}.",
        f"- Blind queries captured: {metrics['privacy']['captured_query_requests']}; "
        f"queries containing any IBAN: {metrics['privacy']['query_requests_containing_an_iban']}.",
        *operator_attack(metrics),
        "",
        "## Verification",
        "",
        f"- {verified['ops_records']} evidence records validated against `spec/schemas/EvidenceRecord.json`.",
        f"- {verified['decisions']} Guardian Decisions, {verified['receipts']} bank receipts and "
        f"{verified['statements']} bank statements: Ed25519 signatures verified.",
        f"- {verified['audit_events']} audit events recomputed from genesis; "
        f"{verified['audit_checkpoints']} signed checkpoints verified.",
        "- metrics.json recomputed from ops.jsonl and found identical.",
        "",
        "## Limitations",
        "",
        *(f"- {item}" for item in metrics["limitations"]),
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------- README results block
README_START = "<!-- results:start -->"
README_END = "<!-- results:end -->"


def readme_block(metrics: dict[str, Any]) -> str:
    """The README's results section: the same table as EVIDENCE.md, from the same metrics.json."""
    seed, network = metrics["seed"], metrics["network"]
    lines = [
        README_START,
        f"<!-- generated by `make evidence SEED={seed}` from evidence/run-{seed}/metrics.json; "
        "do not edit by hand -->",
        "",
        f"Run `{metrics['run_id']}` ({metrics['mode']}). {metrics['disclosure']}",
        "",
        *results(metrics["configs"]),
        "",
        f"Fraud network: {network['stopped_before_payment_b2']} of {network['reported_payee_scenarios']} "
        f"reported-payee scenarios stopped before payment with the network (B2), "
        f"{network['stopped_before_payment_b1']} without it (B1).",
        f"Full report with every residual attack: `evidence/run-{seed}/EVIDENCE.md` (generated). "
        f"Re-check signatures and numbers offline with `make verify-evidence SEED={seed}`.",
        "",
        README_END,
    ]
    return "\n".join(lines)


def _split_readme(text: str) -> tuple[str, str, str] | None:
    start, end = text.find(README_START), text.find(README_END)
    if start < 0 or end < start:
        return None
    return text[:start], text[start : end + len(README_END)], text[end + len(README_END) :]


def sync_readme(path: Path, metrics: dict[str, Any]) -> bool:
    """Replace the README results block; False when the README has no block markers."""
    parts = _split_readme(path.read_text(encoding="utf-8"))
    if parts is None:
        return False
    before, _, after = parts
    path.write_text(before + readme_block(metrics) + after, encoding="utf-8")
    return True


def readme_status(path: Path, metrics: dict[str, Any]) -> str:
    """'in_sync', 'stale' (block shows this run with other numbers), 'other_run' or 'no_block'."""
    parts = _split_readme(path.read_text(encoding="utf-8"))
    if parts is None:
        return "no_block"
    block = parts[1]
    if block == readme_block(metrics):
        return "in_sync"
    return "stale" if f"Run `{metrics['run_id']}`" in block else "other_run"


def operator_attack(metrics: dict[str, Any]) -> list[str]:
    attack = metrics["privacy"].get("operator_attack")
    if not attack:
        return ["- Operator privacy attack: not run for this bundle."]
    return [
        f"- Operator privacy attack (server transcript + every epoch key + {attack['candidates_checked']:,} "
        f"candidate IBANs): {attack['recovered_identifiers']} identifiers recovered, "
        f"{attack['repeated_blinded_elements']} repeated blinded elements across "
        f"{attack['blinded_elements']} sent. Control (a client sending SHA-256 of the IBAN): "
        f"{attack['control_recovered_identifiers']} of {attack['true_payees']} payees recovered.",
    ]
