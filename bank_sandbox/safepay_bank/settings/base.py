def env(name: str, default: str = "") -> str:
    return os.environ.get(name, default)


def secret(name: str, default: str = "") -> str:
    """Read NAME from the environment, else from the file at NAME_FILE (docker secrets style)."""
    if name in os.environ:
        return os.environ[name]
    path = os.environ.get(f"{name}_FILE")
    if path and Path(path).is_file():
        return Path(path).read_text(encoding="utf-8").strip()
    return default


def dev_secret(name: str) -> str:
    """Secret generated by ops/scripts/gen_dev_keys.py (local dev and tests only)."""
    path = Path(env("SAFEPAY_KEYS_DIR", str(REPO_DIR / "ops" / "dev-keys"))) / "secrets" / name
    return path.read_text(encoding="utf-8").strip() if path.is_file() else ""


